function icon(name, extraClass = '') {
  const body = ICONS[name] || '';
  return `<svg class="ic ${extraClass}" viewBox="0 0 24 24" aria-hidden="true">${body}</svg>`;
}

// Troca cada <i data-ic="nome"></i> do HTML por um <svg> equivalente, preservando as classes.
function hydrateIcons(root = document) {
  root.querySelectorAll('[data-ic]').forEach(el => {
    const holder = document.createElement('template');
    holder.innerHTML = icon(el.dataset.ic, el.className);
    el.replaceWith(holder.content.firstChild);
  });
}

document.addEventListener('DOMContentLoaded', () => hydrateIcons());
